package i8080

// OpInfo describes one opcode: its mnemonic, length in bytes and cycle count.
//
// In Mnemonic, "d8" stands for an immediate byte, "d16" for an immediate word
// and "a16" for an address; Disassemble fills them in.
type OpInfo struct {
	Mnemonic     string
	Length       int
	Cycles       int  // cycles when a condition is false (or the only count)
	CyclesTaken  int  // cycles when a conditional call or return is taken
	Undocumented bool // an undocumented alias of another instruction (DESIGN §6.1)
}

// Op returns the description of an opcode.
